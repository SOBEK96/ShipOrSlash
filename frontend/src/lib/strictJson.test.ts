import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { JsonSyntaxError, PyFloat, isPyInt, parseStrictJson, pyIntValue } from "./strictJson";
import { classifySource, corroborate, type VerifyContext } from "./verify";

describe("integer vs float literals (Python json.loads semantics)", () => {
  it.each(["0", "1", "-1", "-0", "42", "1760000001", "123456789012345678901234567890"])("%s is an integer", (lit) => {
    const v = parseStrictJson(lit);
    expect(isPyInt(v), lit).toBe(true);
  });

  it.each([
    "1.0", "1.00", "0.0", "-0.0", "1e0", "1E0", "1e+0", "1E-0", "10e-1", "0.1e1", "1.0e0", "100e-2",
    "1.0000000000000001", "100000000000000000000e-20", "1e400", "-1e400", "5e-1", "1e2",
  ])("%s is a float, never an integer", (lit) => {
    const v = parseStrictJson(lit);
    expect(v).toBeInstanceOf(PyFloat);
    expect(isPyInt(v)).toBe(false);
  });

  it.each(["NaN", "Infinity", "-Infinity"])("%s is a float (Python's decoder accepts it)", (lit) => {
    const v = parseStrictJson(lit);
    expect(v).toBeInstanceOf(PyFloat);
    expect(isPyInt(v)).toBe(false);
  });

  it("keeps integers beyond 2^53 exact as bigint", () => {
    const v = parseStrictJson("9007199254740993");
    expect(typeof v).toBe("bigint");
    expect(pyIntValue(v as bigint)).toBe(9007199254740993n);
  });

  it("normalises -0 to 0", () => {
    expect(Object.is(parseStrictJson("-0"), 0)).toBe(true);
  });

  it("numbers keep their type inside containers", () => {
    const v = parseStrictJson('{"a": 1, "b": 1.0, "c": [2, 2.0, 2e0]}') as Record<string, unknown>;
    expect(isPyInt(v.a)).toBe(true);
    expect(isPyInt(v.b)).toBe(false);
    const c = v.c as unknown[];
    expect([isPyInt(c[0]), isPyInt(c[1]), isPyInt(c[2])]).toEqual([true, false, false]);
  });

  it("JSON.parse cannot tell these apart, which is why it is not used", () => {
    expect(Number.isInteger(JSON.parse("1.0"))).toBe(true);
    expect(Number.isInteger(JSON.parse("1e0"))).toBe(true);
    expect(Number.isInteger(JSON.parse("1.0000000000000001"))).toBe(true);
  });
});

describe("malformed number syntax is an error (the body is then 'not JSON')", () => {
  it.each([
    "01", "00", "-01", "+1", "1.", ".1", "-", "--1", "1e", "1e+", "1.e5", "0x1", "1_000", "1,5", "Infinit", "nan",
    "١", "1 2", "[01]", '{"a": 01}', '{"a": +1}', '{"a": 1.}', "[1,]", '{"a": 1,}', "{,}", "[1 2]", '{"a" 1}',
  ])("%j", (text) => {
    expect(() => parseStrictJson(text)).toThrow(JsonSyntaxError);
  });
});

describe("other strictness that follows Python's decoder", () => {
  it.each([
    ["a BOM", "﻿{}"],
    ["an unquoted key", "{a: 1}"],
    ["single quotes", "{'a': 1}"],
    ["a raw control character in a string", '"a\u0001b"'],
    ["a raw newline in a string", '"a\nb"'],
    ["an invalid escape", '"\\x41"'],
    ["a short \\u escape", '"\\u12"'],
    ["trailing data", "{} {}"],
    ["trailing garbage", "{}x"],
    ["an unterminated string", '"abc'],
    ["an empty input", ""],
    ["only whitespace", "  \n "],
    ["a comment", "{} // c"],
    ["non-JSON whitespace", " {}"],
  ])("rejects %s", (_n, text) => {
    expect(() => parseStrictJson(text)).toThrow(JsonSyntaxError);
  });

  it("accepts JSON whitespace around values", () => {
    expect(parseStrictJson(" \t\r\n1 \n")).toBe(1);
  });

  it("the last duplicate key wins", () => {
    const v = parseStrictJson('{"a": 1, "a": 2}') as Record<string, unknown>;
    expect(v.a).toBe(2);
  });

  it("does not let __proto__ keys touch the prototype", () => {
    const v = parseStrictJson('{"__proto__": {"x": 1}}') as Record<string, unknown>;
    expect(Object.getPrototypeOf(v)).toBeNull();
    expect(({} as Record<string, unknown>).x).toBeUndefined();
  });

  it("bounds nesting depth", () => {
    expect(() => parseStrictJson("[".repeat(600) + "]".repeat(600))).toThrow(JsonSyntaxError);
    expect(() => parseStrictJson("[".repeat(100) + "]".repeat(100))).not.toThrow();
  });

  it("decodes escapes", () => {
    expect(parseStrictJson('"a\\n\\u0041\\"\\\\\\/"')).toBe('a\nA"\\/');
  });
});

// ---------------------------------------------------------------------------
// Replay of the contract's own decisions. tests/vectors/json_number_parity.json
// is generated by running the real contract (pytest keeps it exact).
// ---------------------------------------------------------------------------
interface NumberCase {
  field: "milestone_id" | "verified_ts";
  spelling: string;
  body: string;
  accepted: boolean;
  verdict: 0 | 1 | 2;
  source_count: number;
}
const vectors = JSON.parse(
  readFileSync(join(__dirname, "../../../tests/vectors/json_number_parity.json"), "utf8"),
) as { cases: NumberCase[] };

const ctx: VerifyContext = {
  repo: "https://github.com/sobek96/shiporslash",
  signer: "d8a87fdcd4224662af9b788cae845191b3bc64b8155eb124fdbe0d506e4fcf10",
  prefix: "v",
  npm: "@sobek96/shiporslash",
  docker: "sobek96/shiporslash",
  milestone: 1,
  previousTag: "",
  usedCommits: [],
  usedDigests: [],
};

describe("number spellings: the preview agrees with the contract on every vector", () => {
  it("has a substantial set of vectors for both fields", () => {
    expect(vectors.cases.filter((c) => c.field === "milestone_id").length).toBeGreaterThanOrEqual(20);
    expect(vectors.cases.filter((c) => c.field === "verified_ts").length).toBeGreaterThanOrEqual(20);
    expect(vectors.cases.some((c) => c.accepted)).toBe(true);
    expect(vectors.cases.some((c) => !c.accepted && c.verdict === 2)).toBe(true); // unparseable -> outage
    expect(vectors.cases.some((c) => !c.accepted && c.verdict === 0)).toBe(true); // wrong type -> failed
  });

  vectors.cases.forEach((c) => {
    it(`${c.field} = ${JSON.stringify(c.spelling)} -> ${c.accepted ? "valid" : c.verdict === 2 ? "unparseable (outage)" : "invalid"}`, () => {
      const r = classifySource(200, c.body, ctx);
      // The same body served by three mirrors, aggregated as the contract does.
      const agg = corroborate([r, r, r]);
      expect(r.state === "CONFIRMED", `state ${r.state}: ${r.reason}`).toBe(c.accepted);
      expect(agg.verdict).toBe(c.verdict);
      expect(agg.sourceCount).toBe(c.source_count);
      // the preview must never call a record valid that the contract rejected
      if (!c.accepted) expect(r.state).not.toBe("CONFIRMED");
    });
  });
});
